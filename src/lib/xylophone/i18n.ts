export function localizeError(lang: Lang, message: string): string {
  if (lang === "en") return message;
  const text = copy[lang];
  if (message.startsWith("Couldn't read “") || message.startsWith('Couldn\'t read "')) return text.badToken;
  if (message.includes("needs a length")) return text.badLength;
  if (message.startsWith("No notes")) return text.noNotes;
  if (message.includes("too long to keep")) return text.tooLong;
  if (message.startsWith("Give the tune")) return text.nameTheTune;
  if (message.startsWith("That name is too long")) return text.nameLong;
  if (message === "Couldn't read that.") return text.unreadable;
  if (message.startsWith("Not enough room")) return text.noRoom;
  return message;
}
