// Bakes the share-card fonts and fox picture into a TS module, because the
// Vercel function cannot read public/ or assets/ at runtime.
// Run: node scripts/build-share-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
const b64 = (p) => readFileSync(new URL(`../${p}`, import.meta.url)).toString("base64");
const out = `// Generated by scripts/build-share-assets.mjs — do not edit.
export const OUTFIT_600 = "${b64("assets/fonts/outfit600.ttf")}";
export const FRAUNCES_600 = "${b64("assets/fonts/fraunces600.ttf")}";
export const FOX_PNG = "${b64("public/fox-mallet.png")}";
`;
writeFileSync(new URL("../src/lib/xylophone/share-assets.gen.ts", import.meta.url), out);
